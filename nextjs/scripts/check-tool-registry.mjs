import assert from "node:assert/strict";
import { readFileSync } from "node:fs";
import vm from "node:vm";
import ts from "typescript";
const code = ts.transpileModule(readFileSync(new URL("../lib/tool-registry.ts", import.meta.url), "utf8"), { compilerOptions: { module: ts.ModuleKind.CommonJS, target: ts.ScriptTarget.ES2022 } }).outputText;
const context = { exports: {} };
vm.runInNewContext(code, context);
const { parseQuerySchema, parseTestArguments } = context.exports;
const schema = parseQuerySchema(JSON.stringify({ type: "object", properties: { q: { type: "string" }, limit: { type: "integer" }, active: { type: "boolean" } }, required: ["q"], additionalProperties: false }));
assert.equal(JSON.stringify(parseTestArguments(schema, { q: "a & b", limit: "0", active: "false" })), JSON.stringify({ q: "a & b", limit: 0, active: false }));
assert.equal(JSON.stringify(parseTestArguments(schema, { q: "hello" })), '{"q":"hello"}');
assert.throws(() => parseTestArguments(schema, {}), /Enter a value for q/);
assert.throws(() => parseTestArguments(schema, { q: "hello", limit: "1.5" }), /integer/);
assert.throws(() => parseTestArguments(schema, { q: "hello", active: "yes" }), /true or false/);
assert.throws(() => parseQuerySchema("invalid"), /valid JSON/);
assert.throws(() => parseQuerySchema('{"type":"object","properties":{"q":{"type":"array"}}}'), /scalar|string/);
assert.throws(() => parseQuerySchema('{"type":"object","properties":{},"required":["missing"]}'), /declared/);
assert.throws(() => parseQuerySchema('{"type":"object","properties":{"q":{"type":"string","pattern":"x"}}}'), /type and description/);
assert.throws(() => parseQuerySchema('{"type":"object","properties":{},"additionalProperties":true}'), /additionalProperties/);
const unusual = parseQuerySchema('{"type":"object","properties":{"constructor":{"type":"string"},"__proto__":{"type":"string"}},"required":["constructor"]}');
assert.throws(() => parseTestArguments(unusual, {}), /constructor/);
assert.equal(JSON.stringify(parseTestArguments(unusual, JSON.parse('{"constructor":"name","__proto__":"value"}'))), '{"constructor":"name","__proto__":"value"}');
console.log("Tool registry schema and test-argument checks passed");
